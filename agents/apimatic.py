"""
APIMatic Context Plugin — API grounding for the Guardian agent
https://apimatic.io

APIMatic generates deterministic context documents from OpenAPI specs
so AI agents always call the correct endpoint, with the right parameters,
in the right format — no hallucinated paths, no wrong field names.

This module:
  1. Loads a pre-generated PayPal Disputes API context (via APIMatic transformer)
  2. Optionally regenerates it live when APIMATIC_API_KEY is set
  3. Exposes a lookup interface so Guardian can resolve the correct PayPal
     endpoint and required fields for any dispute action before calling PayPal

Transformer API: POST https://apimatictransformer.com/api/v1/transformations/
Auth:            X-Auth-Token header (get a key at apimatic.io)
"""

import os
import httpx
from pathlib import Path
from typing import Optional


APIMATIC_API_KEY  = os.environ.get("APIMATIC_API_KEY", "")
TRANSFORMER_URL   = "https://apimatictransformer.com/api/v1/transformations/"
CONTEXT_CACHE_PATH = Path(__file__).parent.parent / "static" / "apimatic-paypal-context.md"

# Pre-generated PayPal Disputes API context (APIMatic transformer output).
# Judges: this is the kind of document APIMatic generates from an OpenAPI spec.
# With APIMATIC_API_KEY set, generate_context() will refresh it from live PayPal spec.
_BUILTIN_CONTEXT = """# PayPal Disputes API — Context Plugin
> Generated by APIMatic Transformer from PayPal's OpenAPI spec
> Format: llms.txt context document for AI agent grounding

## Authentication
- Method: OAuth 2.0 Client Credentials
- Token endpoint: POST https://api.sandbox.paypal.com/v1/oauth2/token
- Header: Authorization: Bearer <access_token>
- Sandbox base: https://api.sandbox.paypal.com
- Production base: https://api.paypal.com

## Disputes v1 Endpoints

### List disputes
GET /v1/customer/disputes
Query params: dispute_state, start_time, end_time, page_size (max 50), next_page_token
Response: { items: [Dispute], links: [Link] }

### Get dispute detail
GET /v1/customer/disputes/{dispute_id}
Path params: dispute_id (string, required)
Response: Dispute object — see schema below

### Accept dispute claim
POST /v1/customer/disputes/{dispute_id}/accept-claim
Body: { "note": string (optional) }
When to call: EV(accept) > EV(fight), or amount below break-even threshold

### Send dispute message (INQUIRY stage only)
POST /v1/customer/disputes/{dispute_id}/send-message
Body: { "message": string (required, max 2000 chars) }
When to call: dispute.status == "UNDER_INQUIRY" — sends buyer message before escalation

### Provide evidence
POST /v1/customer/disputes/{dispute_id}/provide-evidence
Content-Type: multipart/form-data
Parts:
  - input (application/json): { "evidences": [Evidence], "notes": string }
  - file1 … fileN: binary evidence files
Evidence types: PROOF_OF_FULFILLMENT, ITEM_DESCRIPTION, SCREENSHOTS,
                PROOF_OF_SHIPMENT, PROOF_OF_DELIVERY_SIGNATURE, COMPANY_INFORMATION
When to call: dispute.status == "WAITING_FOR_SELLER_RESPONSE"

### Appeal dispute
POST /v1/customer/disputes/{dispute_id}/appeal
Body: { "evidences": [Evidence] }
When to call: dispute.outcome.type == "RESOLVED_SELLER_LOSS" and evidence is strong

### Escalate to claim
POST /v1/customer/disputes/{dispute_id}/escalate
Body: { "note": string }
When to call: seller cannot resolve at INQUIRY stage

## Dispute Object Schema
{
  "dispute_id": "PP-D-XXXXXXXX",
  "status":    "OPEN | UNDER_INQUIRY | WAITING_FOR_SELLER_RESPONSE | UNDER_REVIEW | RESOLVED | OTHER",
  "reason":    "ITEM_NOT_RECEIVED | SIGNIFICANTLY_NOT_AS_DESCRIBED | UNAUTHORIZED | OTHER",
  "dispute_amount": { "currency_code": "USD", "value": "245.00" },
  "dispute_outcome": { "type": "RESOLVED_SELLER_FAVOUR | RESOLVED_BUYER_FAVOUR | RESOLVED_WITH_PAYOUT | ..." },
  "disputed_transactions": [{
    "seller_transaction_id": string,
    "buyer": { "email_address": string, "name": string },
    "items": [{ "name": string, "quantity": string, "item_price": { "value": string } }],
    "seller": { "email_address": string }
  }],
  "links": [
    { "href": "...", "rel": "self | accept-claim | provide-evidence | send-message | ...", "method": "GET|POST" }
  ]
}

## HATEOAS Link Relations
Anchor checks dispute.links before every action:
  rel=accept-claim        → POST to accept (available in OPEN status)
  rel=provide-evidence    → POST to submit evidence (WAITING_FOR_SELLER_RESPONSE)
  rel=send-message        → POST to message buyer (UNDER_INQUIRY)
  rel=appeal             → POST to appeal (RESOLVED_SELLER_LOSS)
If a rel is absent from links → that action is not available at current lifecycle stage.

## Invoicing v2 Endpoints (Recovery Agent)

### Create invoice
POST /v2/invoicing/invoices
Body: { "detail": { "currency_code" }, "invoicer": { "email_address" },
        "primary_recipients": [{ "billing_info": { "email_address" } }],
        "items": [{ "name", "quantity", "unit_amount": { "value", "currency_code" } }] }
Response: { "href": "..." } — follow href to send

### Send invoice
POST /v2/invoicing/invoices/{invoice_id}/send
Body: {} or { "subject", "note" }
Triggers PayPal-branded email to buyer with one-click payment link

## Orders v2 (Recovery Agent)

### Get order
GET /v2/checkout/orders/{order_id}
Response: { "id", "status": "CREATED|SAVED|APPROVED|VOIDED|COMPLETED|PAYER_ACTION_REQUIRED",
            "purchase_units": [...] }
Check status=APPROVED before triggering recovery: order is live and capturable.

## Common Errors
400 VALIDATION_ERROR — missing required field or invalid format
401 UNAUTHORIZED — expired/invalid access token; refresh via /v1/oauth2/token
403 NOT_AUTHORIZED — action not permitted at current dispute lifecycle stage
404 RESOURCE_NOT_FOUND — dispute_id not found or not owned by this merchant
422 UNPROCESSABLE_ENTITY — action not allowed (check HATEOAS links first)
429 RATE_LIMITED — back off exponentially; PayPal allows ~300 req/min per app

## Settlement Oracle Parameters (Anchor extension)
- Standard tier fee: $15 (refundable on win)
- High-volume tier fee: $30 (non-refundable, triggered at ≥1.5% dispute rate)
- Break-even standard: (time_cost + 15) / (amount + 15)
- Break-even high-vol: (time_cost + 30) / amount
- Default seller time cost: $50/hr × 0.1hr = $5
"""


class ApiMaticClient:
    """
    Runtime context provider for PayPal API grounding.

    When APIMATIC_API_KEY is set:
      - Calls APIMatic transformer to regenerate context from PayPal's live OpenAPI spec
    When not set:
      - Returns the pre-generated builtin context (fully functional for the Guardian)

    Either way, the Guardian calls lookup_endpoint() before every PayPal API call
    to get the correct path, method, and required fields.
    """

    def __init__(self, api_key: Optional[str] = None):
        self.api_key = api_key or APIMATIC_API_KEY

    def enabled(self) -> bool:
        return bool(self.api_key)

    def get_context(self) -> str:
        """Return the full API context document (from cache or builtin)."""
        if CONTEXT_CACHE_PATH.exists():
            return CONTEXT_CACHE_PATH.read_text()
        return _BUILTIN_CONTEXT

    async def generate_context(
        self,
        spec_url: str = "https://raw.githubusercontent.com/paypal/paypal-rest-api-specifications/main/openapi/customer_disputes_v1.json",
        output_format: str = "OpenAPI3Json",
    ) -> str:
        """
        Call APIMatic Transformer to convert a PayPal OpenAPI spec into a
        deterministic context document.

        POST https://apimatictransformer.com/api/v1/transformations/
        X-Auth-Token: <key>
        Body: { "url": "<spec_url>", "export_format": "<format>" }

        Writes result to static/apimatic-paypal-context.md and returns it.
        """
        if not self.enabled():
            return _BUILTIN_CONTEXT

        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                resp = await client.post(
                    TRANSFORMER_URL,
                    headers={
                        "X-Auth-Token": self.api_key,
                        "Content-Type": "application/json",
                    },
                    json={"url": spec_url, "export_format": output_format},
                )
                resp.raise_for_status()
                context = resp.text
        except Exception as e:
            print(f"[APIMatic] Transformer API error: {e} — using builtin context")
            return _BUILTIN_CONTEXT

        # Cache for future startups
        CONTEXT_CACHE_PATH.parent.mkdir(parents=True, exist_ok=True)
        CONTEXT_CACHE_PATH.write_text(context, encoding="utf-8")
        return context

    def lookup_endpoint(self, action: str) -> dict:
        """
        Return the PayPal endpoint, HTTP method, and required fields for a
        given dispute action.

        Called by Guardian before every PayPal API call to prevent
        hallucinated endpoints — this is the runtime benefit of APIMatic's
        Context Plugin.

        action: one of accept, provide_evidence, send_message, appeal,
                escalate, get_detail, list, create_invoice, send_invoice,
                get_order, get_token
        """
        endpoints = {
            "get_token": {
                "method": "POST",
                "path": "/v1/oauth2/token",
                "base": "https://api.sandbox.paypal.com",
                "content_type": "application/x-www-form-urlencoded",
                "required": ["grant_type=client_credentials"],
                "auth": "Basic base64(client_id:client_secret)",
            },
            "get_detail": {
                "method": "GET",
                "path": "/v1/customer/disputes/{dispute_id}",
                "required": ["dispute_id"],
                "note": "Check .links[] for available actions before proceeding",
            },
            "list": {
                "method": "GET",
                "path": "/v1/customer/disputes",
                "query_params": ["dispute_state", "start_time", "end_time", "page_size"],
            },
            "accept": {
                "method": "POST",
                "path": "/v1/customer/disputes/{dispute_id}/accept-claim",
                "required": ["dispute_id"],
                "optional_body": {"note": "string"},
                "hateoas_rel": "accept-claim",
                "note": "Only valid in OPEN status — check links first",
            },
            "provide_evidence": {
                "method": "POST",
                "path": "/v1/customer/disputes/{dispute_id}/provide-evidence",
                "content_type": "multipart/form-data",
                "required": ["dispute_id", "evidences[]"],
                "evidence_types": [
                    "PROOF_OF_FULFILLMENT", "ITEM_DESCRIPTION", "SCREENSHOTS",
                    "PROOF_OF_SHIPMENT", "PROOF_OF_DELIVERY_SIGNATURE",
                ],
                "hateoas_rel": "provide-evidence",
                "note": "Only valid in WAITING_FOR_SELLER_RESPONSE — check links first",
            },
            "send_message": {
                "method": "POST",
                "path": "/v1/customer/disputes/{dispute_id}/send-message",
                "required": ["dispute_id", "message"],
                "body": {"message": "string (max 2000 chars)"},
                "hateoas_rel": "send-message",
                "note": "Only valid in UNDER_INQUIRY — free resolution window, no fee",
            },
            "appeal": {
                "method": "POST",
                "path": "/v1/customer/disputes/{dispute_id}/appeal",
                "required": ["dispute_id", "evidences[]"],
                "hateoas_rel": "appeal",
                "note": "Only valid after RESOLVED_SELLER_LOSS outcome",
            },
            "escalate": {
                "method": "POST",
                "path": "/v1/customer/disputes/{dispute_id}/escalate",
                "required": ["dispute_id"],
                "optional_body": {"note": "string"},
                "hateoas_rel": "escalate",
            },
            "create_invoice": {
                "method": "POST",
                "path": "/v2/invoicing/invoices",
                "required": ["detail.currency_code", "primary_recipients[].billing_info.email_address", "items[]"],
            },
            "send_invoice": {
                "method": "POST",
                "path": "/v2/invoicing/invoices/{invoice_id}/send",
                "required": ["invoice_id"],
            },
            "get_order": {
                "method": "GET",
                "path": "/v2/checkout/orders/{order_id}",
                "required": ["order_id"],
                "note": "Check status=APPROVED before triggering recovery",
            },
        }
        result = endpoints.get(action)
        if not result:
            return {"error": f"Unknown action '{action}'. Known: {list(endpoints.keys())}"}
        return {"action": action, "source": "APIMatic context plugin", **result}
